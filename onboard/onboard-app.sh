#!/usr/bin/env bash
# Onboard an existing NestJS or Next.js application onto the RSSB platform with
# one command (proposal 3, objective 9).
#
#   onboard/onboard-app.sh --name orders-api --type nestjs \
#       --app-dir ~/code/orders-api --config-dir ~/code/rssb-config [--port 3000] [--database]
#
# App repo:    Dockerfile, .dockerignore, .hadolint.yaml, .trivyignore,
#              .github/workflows/{pr-checks,build-push}.yaml, .github/dependabot.yml
# Config repo: apps/<name>/values.yaml and values-{uat,staging,prod}.yaml
#              (the ApplicationSets deploy every apps/* folder automatically)
#
# Existing files are never overwritten. Review the result, then commit both repos.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
T="$HERE/templates"

NAME="" TYPE="" APP_DIR="" CONFIG_DIR="" PORT="" DATABASE=false
OWNER="${RSSB_GITHUB_OWNER:-KAMAHORO123}"
DOMAIN="${RSSB_DOMAIN:-127.0.0.1.nip.io}"

usage() { sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }
while [ $# -gt 0 ]; do
  case "$1" in
    --name) NAME="$2"; shift 2 ;;
    --type) TYPE="$2"; shift 2 ;;
    --app-dir) APP_DIR="$2"; shift 2 ;;
    --config-dir) CONFIG_DIR="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --database) DATABASE=true; shift ;;
    -h|--help) usage ;;
    *) echo "unknown option: $1" >&2; usage ;;
  esac
done

[ -n "$NAME" ] && [ -n "$TYPE" ] && [ -n "$APP_DIR" ] && [ -n "$CONFIG_DIR" ] || usage
[[ "$NAME" =~ ^[a-z0-9]([a-z0-9-]{0,40}[a-z0-9])?$ ]] || { echo "--name must be a DNS label (lowercase, digits, -)" >&2; exit 1; }
case "$TYPE" in
  nestjs) PORT="${PORT:-3000}"; LIVENESS=/health ;;
  nextjs) PORT="${PORT:-3000}"; LIVENESS=/ ;;
  *) echo "--type must be nestjs or nextjs" >&2; exit 1 ;;
esac
[ -f "$APP_DIR/package.json" ] || { echo "$APP_DIR has no package.json" >&2; exit 1; }
[ -f "$APP_DIR/package-lock.json" ] || { echo "$APP_DIR has no package-lock.json (needed for npm ci)" >&2; exit 1; }
[ -d "$CONFIG_DIR/charts/generic-app" ] || { echo "$CONFIG_DIR is not the config repo" >&2; exit 1; }
[ ! -e "$CONFIG_DIR/apps/$NAME" ] || { echo "apps/$NAME already exists in the config repo" >&2; exit 1; }
if [ "$TYPE" = nextjs ] && ! grep -q "standalone" "$APP_DIR"/next.config.* 2>/dev/null; then
  echo "warning: add  output: \"standalone\"  to next.config.js before building" >&2
fi

CONFIG_REPO="$(git -C "$CONFIG_DIR" remote get-url origin | sed -E 's#(git@github.com:|https://github.com/)##; s#\.git$##')"
IMAGE="ghcr.io/$(echo "$OWNER" | tr '[:upper:]' '[:lower:]')/$NAME"

# Copy a template unless the target exists; replace placeholders.
put() {
  local src="$1" dst="$2"
  if [ -e "$dst" ]; then echo "  keep     ${dst#"$APP_DIR"/}"; return; fi
  mkdir -p "$(dirname "$dst")"
  sed -e "s|__NAME__|$NAME|g" -e "s|__PORT__|$PORT|g" -e "s|__CONFIG_REPO__|$CONFIG_REPO|g" "$src" > "$dst"
  echo "  created  ${dst#"$APP_DIR"/}"
}

echo "App repo: $APP_DIR"
put "$T/$TYPE/Dockerfile"           "$APP_DIR/Dockerfile"
put "$T/common/dockerignore"        "$APP_DIR/.dockerignore"
put "$T/common/hadolint.yaml"       "$APP_DIR/.hadolint.yaml"
put "$T/common/trivyignore"         "$APP_DIR/.trivyignore"
put "$T/common/pr-checks.yaml"      "$APP_DIR/.github/workflows/pr-checks.yaml"
put "$T/common/build-push.yaml"     "$APP_DIR/.github/workflows/build-push.yaml"
put "$T/common/dependabot.yml"      "$APP_DIR/.github/dependabot.yml"

echo "Config repo: $CONFIG_DIR/apps/$NAME"
A="$CONFIG_DIR/apps/$NAME"; mkdir -p "$A"
{
  echo "# $NAME ($TYPE): settings shared by every environment. Generated by rssb-infra/onboard."
  echo "image:"
  echo "  repository: $IMAGE"
  echo
  echo "containerPort: $PORT"
  if [ "$DATABASE" = true ]; then
    echo "existingSecret: $NAME-secrets   # DATABASE_URL etc. (Sealed Secret per namespace)"
    echo "database:"
    echo "  access: true"
  fi
  echo
  echo "livenessProbe:"
  echo "  httpGet: { path: $LIVENESS, port: http }"
  echo "  periodSeconds: 10"
  echo "readinessProbe:"
  echo "  httpGet: { path: $LIVENESS, port: http }"
  echo "  periodSeconds: 5"
  [ "$TYPE" = nextjs ] && printf "\nwritableDirs:\n  - /tmp\n  - /app/.next/cache\n"
  echo
  echo "ingress:"
  echo "  enabled: true"
  echo "  path: /"
  echo "  pathType: Prefix"
} > "$A/values.yaml"
echo "  created  apps/$NAME/values.yaml"
for env in uat staging prod; do
  host="$NAME-$env.$DOMAIN"
  {
    echo "# $NAME in $env."
    echo "image:"
    echo "  tag: pending   # written by CI after the first build on develop"
    echo
    if [ "$env" = prod ]; then
      printf "autoscaling:\n  enabled: true\n  minReplicas: 2\n  maxReplicas: 4\n\npodDisruptionBudget:\n  enabled: true\n"
    else
      echo "replicaCount: 1"
    fi
    printf "\ningress:\n  host: %s\n" "$host"
  } > "$A/values-$env.yaml"
  echo "  created  apps/$NAME/values-$env.yaml  (http://$host)"
done

cat <<EOF

Next steps
  1. App repo: review, commit to a feature branch, open a PR into develop.
  2. GitHub: add the deploy key secret CONFIG_REPO_DEPLOY_KEY to the app repo
     (write access to $CONFIG_REPO), and protect develop/qa/main.
  3. Config repo: commit apps/$NAME in a PR. Argo CD creates $NAME-uat,
     $NAME-staging and $NAME-prod; they stay Degraded until the first image
     exists (merge the app PR into develop).
EOF
[ "$DATABASE" = true ] && cat <<EOF
  4. Database: create logistics-style DB + user per environment, then seal
     $NAME-secrets (DATABASE_URL) for uat, staging and production with kubeseal.
EOF
exit 0
